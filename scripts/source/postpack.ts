import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WORKSPACE_ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");

/** Folder in the workspace root where packed tarballs are copied for local testing. */
export const LOCAL_TESTING_DIR = join(WORKSPACE_ROOT, ".local-testing");

/** Copies the tarball generated by `pack` in the current package into the local testing folder. */
function copyTarball(destination: string) {
  const { name, version } = JSON.parse(readFileSync("package.json", "utf-8"));
  const tarball = `${name.replace("@", "").replace("/", "-")}-${version}.tgz`;

  if (existsSync(tarball)) {
    mkdirSync(destination, { recursive: true });
    copyFileSync(tarball, join(destination, tarball));
  }
}

export default function main(destination = LOCAL_TESTING_DIR) {
  if (existsSync(".build/package.json.orig")) {
    renameSync(".build/package.json.orig", "package.json");
  }

  copyTarball(destination);
}

main();
